import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const WIDTH = 320;
const HEIGHT = 160;
const OUT = "src/lib/dither/land-mask.ts";

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  await readFile(require.resolve("world-atlas/land-110m.json"), "utf8"),
);
const land = feature(topology, topology.objects.land);

const bits = new Uint8Array(Math.ceil((WIDTH * HEIGHT) / 8));
for (let y = 0; y < HEIGHT; y++) {
  const lat = 90 - ((y + 0.5) / HEIGHT) * 180;
  for (let x = 0; x < WIDTH; x++) {
    const lon = ((x + 0.5) / WIDTH) * 360 - 180;
    if (geoContains(land, [lon, lat])) {
      const i = y * WIDTH + x;
      bits[i >> 3] |= 1 << (i & 7);
    }
  }
}

await writeFile(
  OUT,
  `// Generated by scripts/land-mask.mjs from Natural Earth 1:110m land.
export const LAND_WIDTH = ${WIDTH};
export const LAND_HEIGHT = ${HEIGHT};
export const LAND_BITS = "${Buffer.from(bits).toString("base64")}";
`,
);
console.log(`Wrote ${OUT}`);
